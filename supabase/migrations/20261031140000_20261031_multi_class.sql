/*
# Multi-class support — one teacher account, many classes

- New `classes` table: id, name, emoji, per-class goal (target + label).
  Seeded with class #1 ("My Class") — every existing row already belongs to
  it via the class_id columns added back in the first migration.
- `rewards` and `quizzes` gain class_id (students/behaviours/transactions
  already have it). Everything is scoped per class from now on.
- Student-facing scoping tightened: shop rewards and quizzes are only
  visible to students of the SAME class; request_reward and
  approve_redemption enforce it server-side too.
- Class goal moves to the classes table (per class!); the old singleton
  class_goal_progress() is replaced by my_class_goal() which derives the
  student's class from their session and returns that class's goal +
  earned total.
- The class goal columns on class_settings become unused (left in place,
  harmlessly).

All statements idempotent. Existing data lands in class #1 and behaves
exactly as a single class until the teacher creates more.
*/

-- ===== 1. Classes table =====================================================

CREATE TABLE IF NOT EXISTS public.classes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(btrim(name)) >= 1 AND length(name) <= 60),
  emoji text NOT NULL DEFAULT '🎓',
  class_goal_target integer CHECK (class_goal_target IS NULL OR class_goal_target >= 1),
  class_goal_label text,
  created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.classes (id, name, emoji)
SELECT 1,
       COALESCE((SELECT class_name FROM public.class_settings WHERE id = 1), 'My Class'),
       '🎓'
WHERE NOT EXISTS (SELECT 1 FROM public.classes WHERE id = 1);

SELECT setval(pg_get_serial_sequence('public.classes', 'id'),
              GREATEST((SELECT COALESCE(max(id), 1) FROM public.classes), 1));

-- Migrate the singleton goal (if set) onto class #1
UPDATE public.classes c
SET class_goal_target = cs.class_goal_target,
    class_goal_label = cs.class_goal_label
FROM public.class_settings cs
WHERE c.id = 1 AND cs.id = 1
  AND c.class_goal_target IS NULL AND cs.class_goal_target IS NOT NULL;

-- ===== 2. Class scoping on rewards + quizzes ================================

ALTER TABLE public.rewards ADD COLUMN IF NOT EXISTS class_id bigint REFERENCES public.classes(id) ON DELETE CASCADE;
UPDATE public.rewards SET class_id = 1 WHERE class_id IS NULL;
ALTER TABLE public.rewards ALTER COLUMN class_id SET DEFAULT 1;

ALTER TABLE public.quizzes ADD COLUMN IF NOT EXISTS class_id bigint REFERENCES public.classes(id) ON DELETE CASCADE;
UPDATE public.quizzes SET class_id = 1 WHERE class_id IS NULL;
ALTER TABLE public.quizzes ALTER COLUMN class_id SET DEFAULT 1;

CREATE INDEX IF NOT EXISTS idx_rewards_class ON public.rewards(class_id);
CREATE INDEX IF NOT EXISTS idx_quizzes_class ON public.quizzes(class_id);

-- Defaults for the pre-existing class_id columns so plain inserts land
-- somewhere sensible.
ALTER TABLE public.students ALTER COLUMN class_id SET DEFAULT 1;
ALTER TABLE public.behaviors ALTER COLUMN class_id SET DEFAULT 1;
ALTER TABLE public.point_transactions ALTER COLUMN class_id SET DEFAULT 1;

-- ===== 3. RLS on classes ====================================================

ALTER TABLE public.classes ENABLE ROW LEVEL SECURITY;

